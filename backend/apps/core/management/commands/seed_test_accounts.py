"""Create dedicated manual test logins without resetting existing users."""
from datetime import date
from pathlib import Path
import re
import secrets

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from apps.authentication.models import User
from apps.caregivers.models import Caregiver
from apps.clients.models import Client
from apps.core.models import State, Role

MARKER = "<!-- Generated by seed_test_accounts. -->"
STATES = ((1, "FL", "Florida", "florida"), (2, "IN", "Indiana", "indiana"), (3, "GA", "Georgia", "georgia"))


def account_definitions():
    accounts = [("qa.superadmin@example.test", "super_admin", None)]
    for _, code, _, _ in STATES:
        accounts.extend((f"qa.{prefix}.{code.lower()}@example.test", role, code) for prefix, role in (
            ("admin", "administrator"), ("caregiver", "caregiver"), ("client", "client"),
        ))
    return accounts


class Command(BaseCommand):
    help = "Create ten dedicated test accounts and a local credential file. Existing user passwords are preserved."

    def add_arguments(self, parser):
        parser.add_argument("--credentials-file", default=str(settings.BASE_DIR.parent / "TEST_ACCOUNTS.md"))

    def handle(self, *args, **options):
        path = Path(options["credentials_file"]).resolve()
        existing_file = path.exists()
        if existing_file:
            contents = path.read_text(encoding="utf-8")
            match = re.search(r"Shared test password: `([^`\r\n]+)`", contents)
            if MARKER not in contents or match is None:
                raise CommandError("The existing credentials file was not recognized and has been preserved.")
            password = match.group(1)
        else:
            password = "QaTest!42-" + secrets.token_urlsafe(15)

        definitions = account_definitions()
        # Check collisions before creating any state, role, account, or file.
        for email, role, code in definitions:
            user = User.objects.filter(email__iexact=email).select_related("role", "state").first()
            if user is not None and (
                not existing_file or user.role.name != role or (user.state.code if user.state else None) != code
                or not user.check_password(password) or not user.is_authenticated_and_active
            ):
                raise CommandError(f"Existing account {email} was preserved. Resolve its collision before reseeding.")

        created_file = False
        created = 0
        try:
            with transaction.atomic():
                states = {}
                for number, code, name, slug in STATES:
                    state, _ = State.objects.get_or_create(code=code, defaults={"id": number, "name": name, "slug": slug, "active": True})
                    if not state.active:
                        raise CommandError(f"The existing {name} state is inactive and was preserved.")
                    states[code] = state
                roles = {name: Role.objects.get_or_create(name=name)[0] for name in ("super_admin", "administrator", "caregiver", "client")}
                for email, role, code in definitions:
                    user = User.objects.filter(email__iexact=email).first()
                    if user is None:
                        user = User.objects.create_user(
                            email=email, password=password, role=roles[role], state=states.get(code),
                            status="active", is_active=True,
                            is_staff=role == "super_admin", is_superuser=role == "super_admin",
                        )
                        created += 1
                    if role == "caregiver":
                        Caregiver.objects.get_or_create(id=user, defaults={
                            "state": states[code], "first_name": "Test Caregiver", "last_name": states[code].name,
                            "phone": "2025550101", "date_of_birth": date(1990, 1, 1),
                        })
                    if role == "client":
                        Client.objects.get_or_create(id=user, defaults={
                            "state": states[code], "first_name": "Test Client", "last_name": states[code].name,
                            "phone": "2025550102", "date_of_birth": date(1960, 1, 1), "status": "pending",
                        })
                if not existing_file:
                    rows = ["# Test accounts", "", MARKER, "", f"Shared test password: `{password}`", "",
                            "All ten logins use the password above. These are synthetic manual testing accounts.", "",
                            "| Role | State | Email | Login route |", "|---|---|---|---|"]
                    for email, role, code in definitions:
                        route = "/admin/login" if role in ("super_admin", "administrator") else f"/{role}/login"
                        rows.append(f"| {role} | {code or 'All states'} | `{email}` | `{route}` |")
                    rows.extend(["", "Main admin website editor: `/admin/website`.",
                                 "Public visitors use `/florida`, `/indiana`, or `/georgia` without an account.",
                                 "Caregivers start without an application; clients have pending intake profiles.",
                                 "No sample documents, signatures, medical records, or completed training were fabricated.",
                                 "", "Rerun from backend: `venv\\Scripts\\python.exe manage.py seed_test_accounts`.",
                                 "Rerunning preserves these passwords and existing users. This file is ignored by Git.", ""])
                    with path.open("x", encoding="utf-8") as handle:
                        created_file = True
                        handle.write("\n".join(rows))
        except Exception:
            if created_file:
                path.unlink(missing_ok=True)
            raise
        self.stdout.write(self.style.SUCCESS(f"Test accounts ready: {len(definitions)} ({created} created). Credentials: {path}"))
